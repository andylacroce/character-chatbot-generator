/**
 * Generates src/app/theme-tokens.generated.css from packages/shared/src/tokens/ using
 * Style Dictionary — the standard tool for "one set of design tokens, many
 * platform outputs" (it also backs the plain object packages/shared/src/theme.ts
 * exports for the mobile app to read the same colors from). Runs at dev/build time
 * (see predev/build in package.json), the same "generate a build artifact from one
 * source, don't hand-edit it" pattern as docs:api's public/openapi.json.
 *
 * Editing a color means editing packages/shared/src/tokens/{light,dark}.json;
 * editing a font means editing packages/shared/src/tokens/fonts.json. Never edit
 * this script's output, and never author a color/font value in src/app/globals.css.
 */

const fs = require("fs");
const path = require("path");
const StyleDictionary = require("style-dictionary").default;

const TOKENS_DIR = path
  .join(__dirname, "..", "packages", "shared", "src", "tokens")
  .split(path.sep)
  .join("/");
const OUT_PATH = path.join(__dirname, "..", "src", "app", "theme-tokens.generated.css");

const fonts = require(path.join(TOKENS_DIR, "fonts.json"));

/**
 * Runs one Style Dictionary build (light or dark) and returns the formatted CSS
 * block as a string, without writing anything to disk — `formatPlatform` (unlike
 * `buildPlatform`) only formats in memory, which is all a single combined output
 * file needs.
 */
async function buildColorBlock(themeFile, selector, important) {
  const sd = new StyleDictionary({
    log: { verbosity: "silent" },
    source: [`${TOKENS_DIR}/${themeFile}`],
    platforms: {
      css: {
        transformGroup: "css",
        files: [
          {
            destination: "unused.css",
            format: "css/variables",
            options: {
              selector,
              showFileHeader: false,
              formatting: important ? { suffix: " !important;" } : undefined,
            },
          },
        ],
      },
    },
  });
  await sd.hasInitialized;
  const [{ output }] = await sd.formatPlatform("css");
  return output.trim();
}

function fontBlock(selector, important) {
  const bang = important ? " !important" : "";
  const { primary, secondary, mono } = fonts;
  return [
    `${selector} {`,
    `  --font-primary: "${primary.family}", ${primary.fallback}${bang};`,
    `  --font-secondary: "${secondary.family}", ${secondary.fallback}${bang};`,
    `  --font-mono: "${mono.family}", ${mono.fallback}${bang};`,
    `}`,
  ].join("\n");
}

async function main() {
  const [lightBlock, darkBlock] = await Promise.all([
    buildColorBlock("light.json", ":root", false),
    buildColorBlock("dark.json", ".dark", true),
  ]);

  const css = `/* AUTO-GENERATED by scripts/generate-theme-css.cjs (Style Dictionary) from
   packages/shared/src/tokens/{light,dark,fonts}.json — do not edit by hand.
   Regenerated automatically before dev/build (see package.json). */

@import url("${fonts.googleFontsUrl}");

${lightBlock}

${fontBlock(":root", false)}

/* .dark has the same specificity as :root (0,1,0), so these declarations need
   !important to win regardless of import/source order. */
${darkBlock}

${fontBlock(".dark", true)}
`;

  fs.writeFileSync(OUT_PATH, css, "utf8");
  console.log(`Generated ${OUT_PATH} from packages/shared/src/tokens/`);
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
